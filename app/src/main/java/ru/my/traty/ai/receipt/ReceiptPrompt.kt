package ru.my.traty.ai.receipt

import java.time.LocalDate

/**
 * Промпт DeepSeek для текста чека. ИИ только переписывает строки чека в JSON:
 * ничего не складывает и не досчитывает, итог и сверку считает приложение.
 */
object ReceiptPrompt {
    fun system(categories: List<String>, today: LocalDate): String = """
Ты разбираешь текст кассового чека, распознанный с фотографии. Текст может быть с ошибками распознавания.
Чеки бывают разные: продуктовый магазин, строительный, аптека, кафе, маркетплейс.
Верни только JSON без пояснений:
{"store": "название магазина или null", "date": "YYYY-MM-DD или null", "total": "итог чека числом или null",
 "category": "одна категория из списка или null",
 "items": [{"name": "товар", "qty": "количество числом или null", "unit": "шт/кг/л или null", "sum": "сколько заплачено за позицию целиком"}]}
Правила:
- items — только купленные товары и услуги, в порядке чека. Не включай строки ИТОГ, НДС, скидки, бонусы, сдачу, оплату картой, номера ФН/ФД.
- sum — стоимость позиции в чеке (цена × количество, уже со скидкой на эту позицию). Числа переписывай из чека, ничего не придумывай и не складывай.
- Если у товара скидка отдельной строкой, вычти её из sum этого товара.
- name — понятное название по-русски, исправь явные ошибки распознавания, сокращения не расшифровывай, если не уверен. Без артикулов и кодов.
- Если цену товара прочитать нельзя, sum = null.
- total — число из строки ИТОГ / К ОПЛАТЕ. Деньги — числом с точкой: 1234.50.
- store — бренд магазина (как его называют люди: «Пятёрочка», «Леруа Мерлен»), без ООО/АО и адреса.
- date — дата покупки из чека; сегодня $today.
- category — выбери из списка: ${categories.joinToString(", ")}. Если ничего не подходит — null.
""".trimIndent()

    fun user(receiptText: String): String = "Текст чека:\n$receiptText"
}
