package ru.my.traty.data.insights

/**
 * Запрос к ИИ за пояснением к карточке наблюдения. В ИИ уходит только текст самой карточки:
 * названия категорий и суммы, без отдельных трат, мест и заметок. Чистая логика без Android.
 */
object ObservationExplainer {
    const val SYSTEM = "Ты спокойный и доброжелательный личный финансовый помощник. " +
        "Тебе дают одно наблюдение о тратах пользователя. Ответь на русском в 2–3 коротких предложениях: " +
        "какие обычные причины могут за этим стоять (не утверждай, что знаешь причину наверняка) и один небольшой, " +
        "выполнимый совет. Не упрекай и не пугай. Не придумывай цифры, которых нет в наблюдении. " +
        "Без вступлений, без списков, без markdown."

    fun userPrompt(o: Observation): String = "Наблюдение: ${o.title}. ${o.text}"

    /** Ответ без обрамляющих пробелов и лишних звёздочек markdown. */
    fun clean(answer: String): String = answer.replace("**", "").replace("__", "").trim()
}
